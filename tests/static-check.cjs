"use strict";
const fs=require("node:fs"), assert=require("node:assert/strict"), vm=require("node:vm");
const html=fs.readFileSync("index.html","utf8");
const js=html.match(/<script>([\s\S]*?)<\/script>/);
assert(js,"Inline application script must exist");
new vm.Script(js[1],{filename:"app.js"});
const rx=js[1].match(/\{id:"[^"]+",kat:/g)||[];
const kr=js[1].match(/\{id:"[^"]+",ad:/g)||[];
assert.equal(rx.length,83,"Keep 83 prescription records");
assert.equal(kr.length,13,"Keep 13 chronic-care records");
assert.match(js[1],/lact:"Emzirme"/);
assert.match(js[1],/preg:"Gebelik"/);
assert.match(js[1],/function interactionWarnings/);
assert.match(js[1],/function drugBlockers/);
assert.match(js[1],/function drugWarns/);
assert.match(js[1],/function warnLabels/);
assert.match(html,/rel="manifest"/);
assert(html.includes('<script src="./js/clinical-safety.js"></script>'),"Safety module must load before app");
const sw=fs.readFileSync("sw.js","utf8"); new vm.Script(sw,{filename:"sw.js"});
const manifest=JSON.parse(fs.readFileSync("manifest.webmanifest","utf8"));
assert.equal(manifest.name,"DiagnoRx — Tanıdan Reçeteye");
assert.match(sw,/diagnorx-shell-v4/);
assert.match(js[1], /SKIP_WAITING/);
console.log("PASS: syntax, 83 RX, 13 KR, patient-context flags, PWA basics");
