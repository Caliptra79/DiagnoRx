"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {RX,KR}=require("../js/clinical-data.js");
const {buildReport}=require("../scripts/bulk-audit-engine.cjs");
const {validateLeads,reportLeads}=require("../scripts/kub-historical-leads.cjs");
const registry=JSON.parse(fs.readFileSync("audit/kub-historical-leads.json","utf8"));
const report=buildReport({rx:RX,kr:KR});
const q=reportLeads(report,registry);
assert.equal(q.status,"HISTORICAL_IDENTITY_RESEARCH_NOT_CURRENT_KUB");
assert.equal(q.counts.archivalLeads,8);
assert.equal(q.counts.genericMedicineNamesWithHistoricalLead,4);
assert.equal(q.counts.coveredDiagnosisMedicinePairs,86);
assert.equal(q.counts.verifiedCurrentProductKUBs,0);
assert.equal(q.counts.clinicalApprovals,0);
assert(q.leads.every(x=>x.officialKUBVerified===false&&x.currentLicenseVerified===false));
assert(q.leads.every(x=>x.visualSourceChecked===false));
assert.deepEqual(reportLeads(report,registry),q,"Archive report should be deterministic");
const withChange=(field,value)=>({schemaVersion:1,leads:[{...registry.leads[0],[field]:value}]});
assert(validateLeads(withChange("officialKUBVerified",true),report).length>0);
assert(validateLeads(withChange("currentLicenseVerified",true),report).length>0);
assert(validateLeads(withChange("clinicalRegimenApproved",true),report).length>0);
assert(validateLeads(withChange("status","KUB_DOCUMENT_LOCATED"),report).length>0);
assert(validateLeads(withChange("gtin13","8699717010108"),report).length>0);
assert(validateLeads(withChange("sourceUrl","https://fake-sgk.gov.tr/file.pdf"),report).length>0);
assert(validateLeads({schemaVersion:1,leads:[registry.leads[0],registry.leads[0]]},report).length>0);
console.log("PASS: 8 archival government identity leads held back from current KUB/clinical approval");
