"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {RX,KR}=require("../js/clinical-data.js");
const added=require("../js/clinical-additions.js").RX;
const {audit,DRUG,csv}=require("../scripts/manufacturer-parol-review.cjs");
const info=JSON.parse(fs.readFileSync("audit/manufacturer-parol-kub-research.json","utf8"));
const appSrc=fs.readFileSync("js/clinical-data.js","utf8");
const current=audit([...RX,...added],info);
assert.equal(RX.length,83);
assert.equal(KR.length,13);
assert.equal(current.counts.affectedDiagnoses,44,"Shared PCM template or diagnoses unexpectedly changed");
assert.equal(current.counts.affectedMedicineLines,44);
assert.equal(current.counts.findings,4);
assert.equal(current.counts.clinicallyApprovedDiagnoses,0);
assert.equal(current.counts.currentTitckApprovedKubDocuments,0);
assert(info.sources.every(s=>s.currentTitckVersionConfirmed===false));
assert(info.findings.every(x=>x.priority&&x.sourceId&&x.requiredReview));
assert(info.disposition.doseChanged===false);
assert(appSrc.includes('n:"Parasetamol 500 mg tablet"'));
assert(appSrc.includes('s:"3–5 gün"'));
assert(appSrc.includes('üst sınırı 2–3 g tutun'));
assert(current.affected.every(x=>x.uses.every(y=>y.reviewStatus==="INDEPENDENT_CLINICIAN_REVIEW_PENDING")));
assert(csv(current.affected).includes("PAROL_ALCOHOL_LIMIT"));
const synthetic={id:"fake-extra",ad:"Synthetic future",ilac:[{n:DRUG,d:"1x1",s:"1 gün",k:"1 tb"}]};
const grown=audit([...RX,...added,synthetic],info);
assert.equal(grown.counts.affectedDiagnoses,45);
assert.equal(grown.affected.at(-1).diagnosisId,"fake-extra");
assert.equal(grown.counts.clinicallyApprovedDiagnoses,0);
