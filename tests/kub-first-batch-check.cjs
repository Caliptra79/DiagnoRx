"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {RX,KR}=require("../js/clinical-data.js");
const added=require("../js/clinical-additions.js").RX;
const {buildReport,parseStatusMatrix}=require("../scripts/bulk-audit-engine.cjs");
const {makeQueue,validGTIN13}=require("../scripts/review-worklist.cjs");
const {firstBatch,PORTAL}=require("../scripts/kub-first-batch.cjs");
const statuses=parseStatusMatrix(fs.readFileSync("audit/clinical-review-matrix.csv","utf8"));
const report=buildReport({rx:[...RX,...added],kr:KR,reviewStatuses:statuses});
const registry=JSON.parse(fs.readFileSync("audit/medicine-document-register.json","utf8"));
const q=makeQueue(report,registry);
const batch=firstBatch(report,q,8);
assert.equal(batch.status,"OFFICIAL_KUB_DOCUMENT_LOOKUP_PENDING");
assert.equal(batch.sourcePortal,"https://www.titck.gov.tr/kubkt");
assert.equal(batch.sourcePortal,PORTAL);
assert.equal(batch.products.length,8);
assert.deepEqual(batch,firstBatch(report,q,8),"Batch must be deterministic");
assert(batch.products.every(p=>p.clinicalState==="NOT_CLINICALLY_VERIFIED"));
assert(batch.products.every(p=>p.gtin13===""&&p.exactLicensedProduct===""&&p.officialKubDocument===""));
assert(batch.products.every(p=>p.diagnosisCount>0&&p.diagnoses.length===p.diagnosisCount));
assert(batch.products[0].diagnosisCount>=batch.products[1].diagnosisCount);
assert(batch.counts.diagnosisOccurrences===batch.products.reduce((n,p)=>n+p.diagnosisCount,0));
assert.equal(batch.counts.foundProductDocuments,0,"No product-specific KÜB documents verified yet");
assert(validGTIN13("4006381333931"),"Valid GTIN-13 synthetic test");
assert(!validGTIN13("4006381333932"),"GTIN checksum gate must reject changes");
const newRx={id:"future-test",kat:"Synthetic",ad:"Synthetic",icd:"Z00",uygun:"Example",
 kaynak:"Example",sevk:["Example"],oneri:["Example"],ilac:[{n:"Example future product",g:"ana",d:"1x1",s:"1 gün",k:"1 tb"}]};
const grown=buildReport({rx:[...RX,...added,newRx],kr:KR,reviewStatuses:statuses});
const larger=firstBatch(grown,makeQueue(grown,registry),1000);
assert(larger.products.some(p=>p.genericDescription==="Example future product"));
assert.equal(larger.products.find(p=>p.genericDescription==="Example future product").clinicalState,"NOT_CLINICALLY_VERIFIED");
console.log("PASS: KÜB identity requests are prioritized, fail closed, and include future diagnoses");
